function isPrintableText(text) {
  if (!text) return false;
  // strip ASCII control chars (keeping \t \n \r)
  const cleaned = text.replace(/[\x00-\x08\x0B\x0C\x0E-\x1F\x7F]/g, '');
  return cleaned.length / text.length > 0.9;
}

